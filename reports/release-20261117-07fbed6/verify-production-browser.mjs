await page.screenshot({path:out+'/production-home-desktop.png',fullPage:true});
await page.getByRole('button',{name:'入座',exact:true}).click();
await page.getByRole('button',{name:'开一桌',exact:true}).waitFor({state:'visible'});
const before=await me();
