assert.equal((await me()).userId,before.userId);
passed.push('guest entry and refresh preserve identity');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:out+'/production-home-narrow.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
passed.push('390px home has no horizontal overflow');
await page.setViewportSize({width:1440,height:1000});
await page.getByRole('button',{name:'开一桌',exact:true}).click();
await page.getByRole('button',{name:'请 AI 入座',exact:true}).first().waitFor({state:'visible'});
const invite=page.locator('select[aria-label$="号位请 AI 入座的档位"]').first();
assert.deepEqual(await invite.locator('option').allTextContents(),['初级','中级','高级','大师级']);
await invite.selectOption('MASTER');
await page.getByRole('button',{name:'请 AI 入座',exact:true}).first().click();
const level=page.locator('select[aria-label$="号位 AI 档位"]').first();
await level.waitFor({state:'visible'});
assert.equal(await level.inputValue(),'MASTER');
await level.selectOption('ADVANCED');
await page.waitForFunction(()=>document.body.textContent.includes('AI 牌友，高级'));
passed.push('four difficulty choices, invite Master and change to Advanced');
await page.screenshot({path:out+'/production-room.png',fullPage:true});
